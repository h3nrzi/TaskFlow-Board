import { test, expect } from './test';
import { seedWorkspace, waitForSaved, navigate } from './workspace';

test('task assignment and status stay consistent across boards, summaries and reload', async ({ page }) => {
  await seedWorkspace(page);
  await page.goto('/tasks');
  await page.getByTestId('button-create-task').click();
  await expect(page.getByTestId('input-task-project')).toHaveValue('source');
  await page.getByTestId('input-task-title').fill('Moving audit task');
  await page.getByTestId('input-task-description').fill('Keep this context');
  await page.getByTestId('input-task-assignee').fill('Sam');
  await page.getByTestId('input-task-due-date').fill('2026-12-20');
  await page.getByTestId('input-task-priority').selectOption('high');
  await page.getByTestId('button-save-task').click();
  const row = page.getByTestId(/^task-row-/).filter({ hasText: 'Moving audit task' });
  await expect(row).toHaveCount(1);
  const rowId = await row.getAttribute('data-testid');
  const id = rowId!.slice('task-row-'.length);
  await navigate(page, 'overview');
  await expect(page.getByTestId(`task-row-${id}`)).toContainText('Source project');
  await expect(page.getByTestId('project-summary-source')).toContainText('1 tasks');
  await page.getByTestId(`button-open-task-${id}`).click();
  await page.getByTestId('select-drawer-task-status').selectOption('done');
  await page.getByTestId('select-drawer-task-project').selectOption('destination');
  await page.getByTestId('button-close-task-drawer').click();
  const metric = (label: string) => page.locator('.metric-card').filter({ hasText: label }).locator('.metric-value');
  await expect(metric('Open tasks')).toHaveText('0');
  await expect(metric('In progress')).toHaveText('0');
  await expect(metric('Completed')).toHaveText('1');
  await expect(metric('Overall progress')).toHaveText('100%');
  await expect(page.getByTestId('project-summary-source')).toContainText('0 tasks');
  await expect(page.getByTestId('project-summary-destination')).toContainText('1 tasks');
  // Progress is intentionally hidden on narrow screens; the board exposes it there.
  if (page.viewportSize()!.width > 680) await expect(page.getByTestId('project-summary-destination')).toContainText('100% complete');
  await page.getByTestId('project-summary-source').click();
  await expect(page.getByTestId(`board-task-${id}`)).toHaveCount(0);
  await navigate(page, 'projects');
  const destination = page.getByTestId('card-project-destination');
  await expect(destination).toContainText('1 task');
  await expect(destination).toContainText('100%');
  await destination.getByRole('link', { name: 'Destination project', exact: true }).click();
  await expect(page.getByTestId('column-done').getByTestId(`board-task-${id}`)).toContainText('Keep this context');
  await expect(page.getByText('100% complete', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Moving audit task', exact: true }).click();
  await page.getByTestId('select-drawer-task-status').selectOption('in-progress');
  await page.getByTestId('select-drawer-task-project').selectOption('');
  await page.getByTestId('button-close-task-drawer').click();
  await expect(page.getByTestId(`board-task-${id}`)).toHaveCount(0);
  await navigate(page, 'tasks');
  await page.getByTestId('filter-task-project').selectOption('destination');
  await expect(page.getByTestId(/^task-row-/)).toHaveCount(0);
  await page.getByTestId('filter-task-project').selectOption('');
  await expect(page.getByTestId(/^task-row-/)).toHaveCount(1);
  await expect(page.getByTestId(`task-row-${id}`)).toContainText('No project');
  await waitForSaved(page);
  await page.reload();
  await page.getByTestId(`button-open-task-${id}`).click();
  await expect(page.getByTestId('drawer-task-details')).toContainText('Keep this context');
  await expect(page.getByTestId('select-drawer-task-project')).toHaveValue('');
  await expect(page.getByTestId('select-drawer-task-status')).toHaveValue('in-progress');
  await expect(page.getByTestId('select-drawer-task-priority')).toHaveValue('high');
  await expect(page.getByTestId('input-drawer-task-date')).toHaveValue('2026-12-20');
  await expect(page.getByTestId('input-drawer-assignee')).toHaveValue('Sam');
  await page.getByTestId('button-close-task-drawer').click();
  await navigate(page, 'overview');
  await expect(metric('Open tasks')).toHaveText('1');
  await expect(metric('In progress')).toHaveText('1');
  await expect(metric('Completed')).toHaveText('0');
  await expect(metric('Overall progress')).toHaveText('0%');
  await expect(page.getByTestId('project-summary-destination')).toContainText('0 tasks');
  await expect(page.getByTestId(`task-row-${id}`)).toContainText('No project');
});
